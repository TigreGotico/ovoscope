"""File-based intent test cases for OVOS skills.

Lets skill authors describe expected intent routing as plain-text files
under ``test/end2end/cases/<lang>/`` — adding a phrase, intent, or whole
new language is a pure text edit; no Python required.

Layout
------

::

    test/end2end/cases/
        <lang>/
            <IntentName>.intent.test     # one utterance per line, expected
                                         # to match <IntentName>
            no_match.test                # utterances expected to match
                                         # NO intent of this skill

``#`` comments and blank lines are ignored.

Usage (one call, in a test module owned by the skill)
-----------------------------------------------------

::

    # test/end2end/test_intents.py
    from pathlib import Path
    from ovoscope.intent_cases import register_intent_case_tests

    register_intent_case_tests(
        globals(),
        skill_id="ovos-skill-personal.openvoiceos",
        handlers={
            "WhoAreYou": "PersonalSkill.handle_who_are_you_intent",
            "WhatAreYou": "PersonalSkill.handle_what_are_you_intent",
            # ...
        },
        cases_dir=Path(__file__).parent / "cases",
    )

The call creates four ``unittest.TestCase`` classes in the caller's
module — one per pipeline family (Padatious, Padacioso, Model2Vec) plus
one for the full default OVOS stack — each containing one ``test_*``
method per (lang, utterance) pair. A test passes if any tier of its
pipeline family routes the utterance to the expected intent, which
matches realistic production cascade behaviour.

Override the generated set with ``pipelines={"name": [stage, ...]}`` if
you only want a subset, or to test against custom pipeline stages.
"""
from __future__ import annotations

import atexit
import dataclasses
import time
from copy import deepcopy
from pathlib import Path
from typing import Dict, Iterable, Iterator, List, Optional, Union
from unittest import TestCase

from ovos_bus_client.message import Message
from ovos_bus_client.session import Session
from ovos_utils.log import LOG

# Imports from the top-level package — guarded to avoid a circular import at
# module load. The runtime calls happen well after package init.
from ovoscope import (DEFAULT_TEST_PIPELINE, End2EndTest, M2V_PIPELINE,
                      PADACIOSO_PIPELINE, PADATIOUS_PIPELINE, get_minicroft)

__all__ = [
    "IntentCase",
    "load_intent_cases",
    "assert_intent_case",
    "register_intent_case_tests",
    "DEFAULT_IGNORE_MESSAGES",
    "DEFAULT_PIPELINE_FAMILIES",
]

DEFAULT_IGNORE_MESSAGES: List[str] = [
    "speak",
    "mycroft.audio.play_sound",
    "ovos.common_play.stop.response",
]

# Named pipeline families generated by default.
DEFAULT_PIPELINE_FAMILIES: Dict[str, List[str]] = {
    "Padatious": PADATIOUS_PIPELINE,
    "Padacioso": PADACIOSO_PIPELINE,
    "M2V": M2V_PIPELINE,
    "DefaultPipeline": DEFAULT_TEST_PIPELINE,
}


@dataclasses.dataclass(frozen=True)
class IntentCase:
    """A single expectation: ``utterance`` in ``lang`` should match ``intent``.

    ``intent`` is ``None`` to assert no intent of the skill under test
    fires (the utterance falls through to ``complete_intent_failure``).
    """
    lang: str
    utterance: str
    intent: Optional[str]
    source: Path


# ---------------------------------------------------------------------------
# Case-file discovery
# ---------------------------------------------------------------------------
def canonical_intent(name):
    """Fold the legacy ``<file>.intent`` id onto the OVOS-INTENT-4 canonical
    suffixless id. Matcher plugins (ovos-padatious >= 2.0) dealias at
    registration, so engine matches carry the suffixless name; case files keep
    the ``<Intent>.intent.test`` naming, and suffixed entries in
    ``known_intents``/``handlers`` are accepted and folded the same way."""
    if name and name.endswith(".intent"):
        return name[:-len(".intent")]
    return name


def _read_lines(path: Path) -> List[str]:
    out: List[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out


def load_intent_cases(cases_dir: Union[str, Path],
                      known_intents: Optional[Iterable[str]] = None
                      ) -> List[IntentCase]:
    """Discover every ``IntentCase`` under ``cases_dir``.

    Args:
        cases_dir: directory containing ``<lang>/<Intent>.intent.test`` and
            optionally ``<lang>/no_match.test`` files.
        known_intents: if given, every ``<Intent>.intent`` filename found
            is validated against this set — a typo will raise
            ``AssertionError`` instead of silently being skipped.

    Returns:
        List of cases in stable (lang, file, line) order.
    """
    base = Path(cases_dir)
    if not base.is_dir():
        return []
    known = ({canonical_intent(i) for i in known_intents}
             if known_intents is not None else None)
    cases: List[IntentCase] = []
    for lang_dir in sorted(base.iterdir()):
        if not lang_dir.is_dir() or lang_dir.name.startswith("_"):
            continue
        lang = lang_dir.name
        for case_file in sorted(lang_dir.glob("*.test")):
            if case_file.name == "no_match.test":
                expected: Optional[str] = None
            elif case_file.stem.endswith(".intent"):
                # engine matches are suffixless (OVOS-INTENT-4 canonical id)
                expected = canonical_intent(case_file.stem)
                if known is not None and expected not in known:
                    raise AssertionError(
                        f"{case_file} targets unknown intent "
                        f"{expected!r}; expected one of {sorted(known)}")
            else:
                continue
            for utt in _read_lines(case_file):
                cases.append(IntentCase(lang=lang, utterance=utt,
                                        intent=expected, source=case_file))
    return cases


# ---------------------------------------------------------------------------
# Single-case assertion
# ---------------------------------------------------------------------------
def assert_intent_case(minicroft, skill_id: str, handlers: Dict[str, str],
                       case: IntentCase, pipeline: List[str],
                       *,
                       ignore_messages: Optional[List[str]] = None,
                       timeout: float = 30) -> None:
    """Fire ``case.utterance`` through ``pipeline`` and assert routing.

    Asserts that an ``IntentCase`` with ``intent=None`` falls through to
    ``complete_intent_failure``; otherwise asserts the expected intent
    and handler-lifecycle messages fire in order.

    Args:
        minicroft: a running ``MiniCroft`` instance with ``skill_id`` loaded.
        skill_id: the full skill id under test (e.g. ``"my-skill.author"``).
        handlers: ``{intent_name: handler_method_name}`` for the skill.
        case: the case to run.
        pipeline: list of pipeline stage ids to populate
            ``session.pipeline`` with.
        ignore_messages: extra non-deterministic / noisy message types to
            filter out of the comparison.
        timeout: per-case execution timeout, in seconds.
    """
    ignored = list(ignore_messages or DEFAULT_IGNORE_MESSAGES)

    session = Session(f"intent-case-{case.lang}-{case.utterance[:24]}")
    session.lang = case.lang
    session.pipeline = list(pipeline)

    source = Message(
        "recognizer_loop:utterance",
        {"utterances": [case.utterance], "lang": case.lang},
        {"session": session.serialize()},
    )

    if case.intent is None:
        final_session = deepcopy(session)
        expected_messages = [
            source,
            Message("complete_intent_failure",
                    {"utterances": [case.utterance], "lang": case.lang}, {}),
            Message("ovos.utterance.handled", {}, {}),
        ]
        test = End2EndTest(
            minicroft=minicroft,
            skill_ids=[skill_id],
            eof_msgs=["ovos.utterance.handled"],
            flip_points=["recognizer_loop:utterance"],
            ignore_messages=ignored,
            source_message=source,
            final_session=final_session,
            expected_messages=expected_messages,
            test_msg_data=False,
            test_msg_context=False,
        )
    else:
        handlers = {canonical_intent(k): v for k, v in handlers.items()}
        if case.intent not in handlers:
            raise AssertionError(
                f"No handler mapping for intent {case.intent!r} "
                f"(case from {case.source}). Add it to ``handlers``.")
        handler = handlers[case.intent]
        final_session = deepcopy(session)
        final_session.active_skills = [(skill_id, 0.0)]
        expected_messages = [
            source,
            Message(f"{skill_id}.activate", {}, {"skill_id": skill_id}),
            Message(f"{skill_id}:{case.intent}",
                    {"utterance": case.utterance, "lang": case.lang},
                    {"skill_id": skill_id}),
            Message("mycroft.skill.handler.start",
                    {"name": handler}, {"skill_id": skill_id}),
            Message("mycroft.skill.handler.complete",
                    {"name": handler}, {"skill_id": skill_id}),
            Message("ovos.utterance.handled", {}, {"skill_id": skill_id}),
        ]
        test = End2EndTest(
            minicroft=minicroft,
            skill_ids=[skill_id],
            eof_msgs=["ovos.utterance.handled"],
            flip_points=["recognizer_loop:utterance"],
            ignore_messages=ignored,
            source_message=source,
            final_session=final_session,
            activation_points=[f"{skill_id}:{case.intent}"],
            expected_messages=expected_messages,
        )
    test.execute(timeout=timeout)


# ---------------------------------------------------------------------------
# Shared minicroft helper
# ---------------------------------------------------------------------------
_SHARED_MINICROFT_KEY = "_ovoscope_shared_minicroft"


def _wait_for_m2v_sync(mc, max_wait: float = 15.0,
                       quiet_window: float = 0.5) -> float:
    """Wait deterministically for the m2v pipeline to finish its
    ``handle_sync_intents`` debounce after ``mycroft.ready``.

    The m2v plugin (`ovos_m2v_pipeline/__init__.py:handle_sync_intents`)
    sleeps 3 s then re-queries the adapt + padatious intent manifests.
    Until that returns, the pipeline matches against an empty label set
    and every utterance falls through. We avoid relying on a fixed
    ``time.sleep`` by:

      1. Subscribing to every ``padatious:register_intent`` /
         ``register_intent`` event on the bus.
      2. Emitting ``mycroft.ready`` (which triggers
         ``handle_sync_intents``).
      3. Waiting until no new register events have arrived for
         ``quiet_window`` seconds AND at least one register event has
         actually been observed (or ``max_wait`` is exhausted).
      4. Adding a small constant grace period for the in-plugin
         ``time.sleep(3)`` debounce to actually return.

    Returns the seconds slept (for diagnostics).
    """
    seen = {"count": 0, "last_t": 0.0}

    def on_register(_serialized):
        seen["count"] += 1
        seen["last_t"] = time.monotonic()

    def on_padatious(_):
        on_register(None)

    def on_adapt(_):
        on_register(None)

    # Wildcard "message" listener catches the serialized form on FakeBus.
    def on_any(serialized):
        try:
            t = serialized.get("type") if isinstance(serialized, dict) else None
        except Exception:
            return
        if not t:
            return
        if t == "padatious:register_intent" or t == "register_intent":
            on_register(None)

    mc.bus.ee.on("padatious:register_intent", on_padatious)
    mc.bus.ee.on("register_intent", on_adapt)
    mc.bus.ee.on("message", on_any)

    t0 = time.monotonic()
    try:
        mc.bus.emit(Message("mycroft.ready", {}, {}))

        # Wait for the burst of register events to settle.
        while time.monotonic() - t0 < max_wait:
            time.sleep(0.1)
            if seen["count"] > 0 and (time.monotonic() - seen["last_t"]) > quiet_window:
                break
        if seen["count"] > 0:
            # Register events arrived AND went quiet — the sync is observably
            # finished, so there is nothing left to wait for.
            return time.monotonic() - t0
        # Nothing was observed. We cannot tell whether m2v is mid-sync, so pad
        # for the ceiling of its internal time.sleep(3) in handle_sync_intents.
        time.sleep(3.5)
        return time.monotonic() - t0
    finally:
        # Always detach: these listeners live on the shared MiniCroft bus and
        # would keep counting for the rest of the process.
        for topic, handler in (("padatious:register_intent", on_padatious),
                               ("register_intent", on_adapt),
                               ("message", on_any)):
            try:
                mc.bus.ee.remove_listener(topic, handler)
            except Exception:
                pass


def stop_shared_minicrofts() -> None:
    """Stop every cached shared MiniCroft and empty the cache.

    Registered with :mod:`atexit`; also safe to call from a session-scoped
    fixture. A MiniCroft that is never stopped keeps its patches on the
    process-wide ``SessionManager`` and ``Configuration``.
    """
    cache = globals().get(_SHARED_MINICROFT_KEY) or {}
    for mc in list(cache.values()):
        try:
            mc.stop()
        except Exception:
            pass
    cache.clear()


atexit.register(stop_shared_minicrofts)


def _shared_minicroft(skill_id: str, langs: List[str], m2v_warmup: float):
    """Lazily create one MiniCroft and warm m2v's label index.

    Caches the instance on a process-global so every generated class
    shares the same boot. ``m2v_warmup`` is now an *upper bound*: if the
    deterministic event-based wait finishes faster, we return early.

    At most ONE instance stays alive: MiniCroft patches process-wide globals,
    so a second live instance would clobber the first. Requesting a different
    key stops the cached instance before booting the new one.
    """
    cache = globals().setdefault(_SHARED_MINICROFT_KEY, {})
    key = (skill_id, tuple(langs))
    if key not in cache:
        # Keep at most one live MiniCroft — two of them fight over the same
        # SessionManager / Configuration globals.
        for stale_key in [k for k in cache if k != key]:
            stale = cache.pop(stale_key)
            try:
                stale.stop()
            except Exception:
                pass
        LOG.set_level("CRITICAL")
        secondary = [l for l in langs if l != "en-US"]
        mc = get_minicroft([skill_id], secondary_langs=secondary or None)
        if m2v_warmup > 0:
            try:
                _wait_for_m2v_sync(mc, max_wait=max(m2v_warmup, 5.0))
            except Exception:
                # If the deterministic wait fails for any reason
                # (e.g. FakeBus internals change), fall back to a sleep
                # so the suite still runs.
                mc.bus.emit(Message("mycroft.ready", {}, {}))
                time.sleep(m2v_warmup)
        cache[key] = mc
    return cache[key]


# ---------------------------------------------------------------------------
# Test-class generator
# ---------------------------------------------------------------------------
def _slug(s: str) -> str:
    out = []
    for ch in s:
        if ch.isalnum():
            out.append(ch)
        elif ch in " -_/":
            out.append("_")
    return "".join(out).strip("_") or "x"


def _build_test_class(name: str, pipeline: List[str], cases: List[IntentCase],
                      skill_id: str, handlers: Dict[str, str],
                      langs: List[str],
                      ignore_messages: Optional[List[str]],
                      timeout: float,
                      m2v_warmup: float,
                      doc: str) -> type:
    def _make(case: IntentCase):
        def _test(self):
            mc = _shared_minicroft(skill_id, langs, m2v_warmup)
            assert_intent_case(mc, skill_id, handlers, case, pipeline,
                               ignore_messages=ignore_messages,
                               timeout=timeout)
        label = case.intent.split(".")[0] if case.intent else "no_match"
        _test.__doc__ = (f"[{case.lang}] {case.utterance!r} -> "
                         f"{case.intent if case.intent else 'no match'}  ({name})")
        # Attach metadata for the pytest accuracy/coverage reporter.
        _test._intent_case = case  # type: ignore[attr-defined]
        _test._intent_case_pipeline = name  # type: ignore[attr-defined]
        _test._intent_case_skill_id = skill_id  # type: ignore[attr-defined]
        return _test, label

    body: Dict[str, object] = {"__doc__": doc}
    for case in cases:
        method, label = _make(case)
        slug = _slug(case.utterance)
        attr = f"test_{case.lang.replace('-', '_')}__{label}__{slug}"
        # avoid clobbers if two utterances slug-collide
        base = attr
        n = 2
        while attr in body:
            attr = f"{base}_{n}"
            n += 1
        body[attr] = method
    return type(name, (TestCase,), body)


def register_intent_case_tests(
        target_globals: dict,
        *,
        skill_id: str,
        handlers: Dict[str, str],
        cases_dir: Union[str, Path],
        pipelines: Optional[Dict[str, List[str]]] = None,
        ignore_messages: Optional[List[str]] = None,
        timeout: float = 30,
        m2v_warmup: float = 10.0,
        ) -> Dict[str, type]:
    """Create per-pipeline ``TestCase`` classes in ``target_globals``.

    Args:
        target_globals: pass ``globals()`` from the caller test module —
            generated classes are inserted here so pytest collects them.
        skill_id: full skill plugin id (e.g. ``"my-skill.author"``).
        handlers: mapping ``{"<IntentName>.intent": "<HandlerMethodName>"}``
            covering every intent referenced by case files.
        cases_dir: directory containing ``<lang>/<Intent>.intent.test`` and
            optional ``<lang>/no_match.test`` files.
        pipelines: ``{class_suffix: pipeline_stage_list}`` to override the
            default per-family classes. Each entry becomes a
            ``Test<class_suffix>`` class. Defaults to one class per family
            in :data:`DEFAULT_PIPELINE_FAMILIES`.
        ignore_messages: extra message types to filter out of comparison.
        timeout: per-case execution timeout, in seconds.
        m2v_warmup: seconds to sleep after booting the MiniCroft so the
            m2v pipeline finishes syncing its label index. Set to 0 if
            you're not running m2v cases.

    Returns:
        ``{class_name: class_object}`` for every class created.
    """
    cases = load_intent_cases(cases_dir, known_intents=handlers.keys())
    if not cases:
        # Empty cases dir: skip silently so a freshly-copied template
        # doesn't fail collection before any .test files are added.
        return {}

    langs = sorted({c.lang for c in cases})
    families = pipelines if pipelines is not None else DEFAULT_PIPELINE_FAMILIES

    created: Dict[str, type] = {}
    for suffix, pipeline in families.items():
        cls_name = f"Test{suffix}"
        doc = (f"ovoscope intent-case tests for {skill_id} on pipeline "
               f"{pipeline!r}.")
        cls = _build_test_class(cls_name, pipeline, cases, skill_id, handlers,
                                langs, ignore_messages, timeout, m2v_warmup,
                                doc)
        target_globals[cls_name] = cls
        created[cls_name] = cls
    # Mark generated classes so the pytest auto-discovery hook can skip a
    # cases_dir whose tests are already registered by an explicit call.
    target_globals["_ovoscope_intent_cases_registered"] = True
    return created


# ---------------------------------------------------------------------------
# Pytest auto-discovery (no Python boilerplate required in the skill).
#
# A skill can opt in by adding a ``conftest.py`` next to its
# ``cases/`` directory containing:
#
#     ovoscope_intent_cases = dict(
#         skill_id="my-skill.author",
#         handlers={"DoX.intent": "MySkill.handle_do_x", ...},
#     )
#
# The ``pytest_collect_directory`` hook on the ovoscope pytest plugin
# discovers the conftest, walks ``<dir>/cases/`` and generates the same
# TestCase classes ``register_intent_case_tests`` would have created —
# zero boilerplate in the test module.
# ---------------------------------------------------------------------------
def autodiscover_from_conftest(conftest_dir: Union[str, Path],
                               target_globals: dict) -> Dict[str, type]:
    """Look for ``ovoscope_intent_cases`` config in a conftest namespace
    and call :func:`register_intent_case_tests` accordingly.

    The conftest must expose a dict like::

        ovoscope_intent_cases = {
            "skill_id": "my-skill.author",
            "handlers": {"WhoAreYou.intent": "MySkill.handle_who", ...},
            # optional overrides:
            "cases_dir": "cases",
            "pipelines": {"Custom": [...]},
            "ignore_messages": [...],
            "timeout": 30,
            "m2v_warmup": 10.0,
        }

    Returns ``{}`` if the conftest has no ``ovoscope_intent_cases`` or
    the cases directory does not exist.
    """
    cfg = target_globals.get("ovoscope_intent_cases")
    if not cfg:
        return {}
    base = Path(conftest_dir)
    cases_dir = Path(cfg.get("cases_dir", "cases"))
    if not cases_dir.is_absolute():
        cases_dir = base / cases_dir
    if not cases_dir.is_dir():
        return {}
    return register_intent_case_tests(
        target_globals,
        skill_id=cfg["skill_id"],
        handlers=cfg["handlers"],
        cases_dir=cases_dir,
        pipelines=cfg.get("pipelines"),
        ignore_messages=cfg.get("ignore_messages"),
        timeout=cfg.get("timeout", 30),
        m2v_warmup=cfg.get("m2v_warmup", 10.0),
    )
    return created
